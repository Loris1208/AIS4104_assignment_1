constexpr double magnitude_of(double value)
{
    return value < 0.0 ? -value : value;
}

constexpr bool revolute(const std::array<double, 6> &screw)
{
    const double squared_norm = screw[0] * screw[0] + screw[1] * screw[1] + screw[2] * screw[2];
    const double pitch        = screw[0] * screw[3] + screw[1] * screw[4] + screw[2] * screw[5];
    return magnitude_of(squared_norm - 1.0) <= revolute_tolerance && magnitude_of(pitch) <= revolute_tolerance;
}

template<std::size_t N, typename Holds>
constexpr bool every_entry(const std::array<frozen_chain, N> &table, Holds holds)
{
    for(const frozen_chain &chain : table)
        for(std::size_t entry = 0; entry < most_joints; ++entry)
            if(!holds(entry < chain.joints, chain.space_screws[entry], chain.theta_radians[entry]))
                return false;
    return true;
}

template<std::size_t N>
constexpr bool joint_counts_in_scope(const std::array<frozen_chain, N> &table)
{
    return std::ranges::all_of(table, [](const frozen_chain &chain) { return chain.joints >= 1 && chain.joints <= most_joints; });
}

template<std::size_t N>
constexpr bool holds_a_long_chain(const std::array<frozen_chain, N> &table)
{
    return std::ranges::any_of(table, [](const frozen_chain &chain) { return chain.joints >= 7; });
}

template<std::size_t N>
constexpr bool joint_counts_vary(const std::array<frozen_chain, N> &table)
{
    return std::ranges::any_of(table, [&table](const frozen_chain &chain) { return chain.joints != table.front().joints; });
}

template<std::size_t N>
constexpr bool revolute_throughout(const std::array<frozen_chain, N> &table)
{
    return every_entry(table, [](bool joint, const std::array<double, 6> &screw, double) { return !joint || revolute(screw); });
}

template<std::size_t N>
constexpr bool nothing_past_the_joints(const std::array<frozen_chain, N> &table)
{
    return every_entry(table, [](bool joint, const std::array<double, 6> &screw, double theta) { return joint || (screw == std::array<double, 6>{} && theta == 0.0); });
}

template<std::size_t N>
constexpr bool clear_of_zero(const std::array<frozen_chain, N> &table, double margin)
{
    return every_entry(table, [margin](bool joint, const std::array<double, 6> &, double theta) { return !joint || magnitude_of(theta) >= margin; });
}

static_assert(frozen_chains.size() == 8);
static_assert(joint_counts_in_scope(frozen_chains));
static_assert(holds_a_long_chain(frozen_chains));
static_assert(joint_counts_vary(frozen_chains));
static_assert(revolute_throughout(frozen_chains));
static_assert(nothing_past_the_joints(frozen_chains));
static_assert(clear_of_zero(frozen_chains, graded_angle_margin));

inline Eigen::Matrix4d home_of(const frozen_chain &chain)
{
    return Eigen::Map<const Eigen::Matrix<double, 4, 4, Eigen::RowMajor>>(chain.home.data());
}

inline std::vector<praxis::screw_axis> space_screws_of(const frozen_chain &chain)
{
    std::vector<praxis::screw_axis> screws(chain.joints);
    for(std::size_t joint = 0; joint < chain.joints; ++joint)
        screws[joint] = Eigen::Map<const praxis::screw_axis>(chain.space_screws[joint].data());

    return screws;
}

inline Eigen::VectorXd theta_of(const frozen_chain &chain)
{
    return Eigen::Map<const Eigen::VectorXd>(chain.theta_radians.data(), static_cast<Eigen::Index>(chain.joints));
}

