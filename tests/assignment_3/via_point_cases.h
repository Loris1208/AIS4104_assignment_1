// The greatest entry difference over position, velocity and acceleration, twice. The shortest segment in seconds, and the duration
// tolerance relative to the larger of one second and either duration.
constexpr double via_point_magnitude = 1e-10;
constexpr double via_point_linear    = 1e-10;
constexpr double at_rest_magnitude   = 1e-10;
constexpr double at_rest_linear      = 1e-10;
constexpr double shortest_segment    = 0.05;
constexpr double duration_tolerance  = 1e-12;

constexpr pinned_bound via_point_bound{via_point_magnitude, via_point_linear, bound_standing::at_the_platform, bound_standing::at_the_platform};
constexpr pinned_bound at_rest_bound{at_rest_magnitude, at_rest_linear, bound_standing::at_the_platform, bound_standing::at_the_platform};

// The greatest residual over a segment's four conditions, each joint's difference over the larger of one and either side's
// magnitude, twice.
constexpr double via_segment_magnitude = 1e-10;
constexpr double via_segment_linear    = 1e-10;

constexpr pinned_bound via_segment_bound{via_segment_magnitude, via_segment_linear, bound_standing::at_the_platform, bound_standing::at_the_platform};

// Every segment is sampled at these fractions of it, and a run once more at its last time.
constexpr std::array<double, 4> segment_fractions{0.0, 0.25, 0.5, 0.75};

struct sample_point
{
    std::size_t segment;
    std::size_t index;
    double time;
    bool at_an_end;
};

constexpr bool laid_out(std::size_t index)
{
    const via_point_run &run = via_point_runs[index];
    if(index == 0)
        return run.first == 0 && run.values == 0;

    const via_point_run &before = via_point_runs[index - 1];
    return run.first == before.first + before.points && run.values == before.values + before.points * before.width;
}

constexpr bool well_timed(const via_point_run &run)
{
    if(run.points < 2 || run.width == 0 || via_point_times[run.first] != 0.0)
        return false;
    for(std::size_t k = run.first + 1; k < run.first + run.points; ++k)
        if(!(via_point_times[k - 1] < via_point_times[k] && shortest_segment <= via_point_times[k] - via_point_times[k - 1]))
            return false;

    return true;
}

constexpr bool at_rest(std::size_t index)
{
    const via_point_run &run = via_point_runs[index];
    const auto first         = via_point_velocities.begin() + static_cast<std::ptrdiff_t>(run.values);
    return run.points == 2 && std::all_of(first, first + static_cast<std::ptrdiff_t>(run.points * run.width), [](double velocity) { return velocity == 0.0; });
}

constexpr bool every_run_laid_out()
{
    for(std::size_t index = 0; index < via_point_runs.size(); ++index)
        if(!laid_out(index))
            return false;

    const via_point_run &last = via_point_runs.back();
    return last.first + last.points == via_point_times.size() && last.values + last.points * last.width == via_point_positions.size();
}

static_assert(via_point_positions.size() == via_point_velocities.size());
static_assert(every_run_laid_out());
static_assert(std::ranges::all_of(via_point_runs, well_timed));
static_assert(std::ranges::all_of(at_rest_runs, [](std::size_t index) { return index < via_point_runs.size() && at_rest(index); }));

inline std::vector<sample_point> sample_points(const via_point_run &run)
{
    std::vector<sample_point> points;
    for(std::size_t segment = 0; segment + 1 < run.points; ++segment)
    {
        const double start = via_point_times[run.first + segment];
        const double end   = via_point_times[run.first + segment + 1];
        for(std::size_t k = 0; k < segment_fractions.size(); ++k)
            points.push_back(sample_point{segment, k, start + segment_fractions[k] * (end - start), points.empty()});
    }
    points.push_back(sample_point{run.points - 2, segment_fractions.size(), via_point_times[run.first + run.points - 1], true});

    return points;
}

inline std::vector<praxis::trajectory::via_point> via_points_of(const via_point_run &run)
{
    const auto width = static_cast<Eigen::Index>(run.width);
    std::vector<praxis::trajectory::via_point> points;
    for(std::size_t k = 0; k < run.points; ++k)
    {
        const std::size_t at = run.values + k * run.width;
        points.push_back(praxis::trajectory::via_point{via_point_times[run.first + k], Eigen::Map<const Eigen::VectorXd>(via_point_positions.data() + at, width),
                                                       Eigen::Map<const Eigen::VectorXd>(via_point_velocities.data() + at, width)});
    }

    return points;
}

