constexpr bool zero_past_joints(const joint_pair &pair)
{
    for(std::size_t joint = frozen_chains[pair.subject].joints; joint < most_joints; ++joint)
        if(pair.start[joint] != 0.0 || pair.end[joint] != 0.0)
            return false;
    return true;
}

